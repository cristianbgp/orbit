const BLUEPRINT_FILES = [
  "README.md",
  "01-contexto-y-vision.md",
  "02-alcance-funcional.md",
  "03-arquitectura-informacion-ux.md",
  "04-modelo-dominio.md",
  "05-calendario-timeline.md",
  "06-ejemplo-recurso-apelacion.md",
  "07-sistema-visual.md",
  "08-branding-logo.md",
  "09-componentes-estados.md",
  "10-reglas-interaccion.md",
  "11-roadmap.md",
  "12-decisiones-y-pendientes.md",
  "13-prompt-maestro-codex.md",
  "14-inventario-funcional-implementado.md",
  "15-casos.md",
] as const;

const apiDirectory = new URL("../", import.meta.url);
const repositoryDirectory = new URL("../../", apiDirectory);
const documents = await Promise.all(
  BLUEPRINT_FILES.map(async (document) => ({
    document,
    markdown: await Bun.file(
      new URL(`docs/blueprint/${document}`, repositoryDirectory),
    ).text(),
  })),
);

const output = `// Generated by scripts/generate-help-corpus.ts. Do not edit directly.\nexport const generatedBlueprintDocuments = ${JSON.stringify(documents, null, 2)} as const\n`;

await Bun.write(
  new URL("src/help-assistant/blueprint-documents.generated.ts", apiDirectory),
  output,
);
