CREATE OR REPLACE FUNCTION public.orbit_generate_user_alias(input_name text)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $function$
  WITH source_characters AS (
    SELECT character, position
    FROM regexp_split_to_table(coalesce(input_name, ''), '')
      WITH ORDINALITY AS characters(character, position)
  ),
  usable_name AS (
    SELECT trim(regexp_replace(
      coalesce(string_agg(
        CASE
          WHEN public.orbit_alias_code_point_allowed(ascii(character)) THEN character
          ELSE ' '
        END,
        '' ORDER BY position
      ), ''),
      '\s+',
      ' ',
      'g'
    )) AS value
    FROM source_characters
  ),
  raw_alias AS (
    SELECT CASE
      WHEN value = '' THEN 'ORBIT'
      WHEN array_length(regexp_split_to_array(value, '\s+'), 1) > 1 THEN (
        SELECT string_agg(left(word, 1), '')
        FROM unnest(regexp_split_to_array(value, '\s+')) AS words(word)
      )
      ELSE left(value, 3)
    END AS value
    FROM usable_name
  ),
  upper_alias AS (
    SELECT left(coalesce((
      SELECT string_agg(
        public.orbit_alias_upper(character),
        '' ORDER BY position
      )
      FROM regexp_split_to_table(value, '')
        WITH ORDINALITY AS characters(character, position)
    ), ''), 12) AS candidate
    FROM raw_alias
  ),
  minimum_length_alias AS (
    SELECT CASE
      WHEN char_length(candidate) = 1 THEN candidate || candidate
      ELSE candidate
    END AS candidate
    FROM upper_alias
  )
  SELECT CASE
    WHEN char_length(candidate) BETWEEN 2 AND 12
      AND NOT EXISTS (
        SELECT 1
        FROM regexp_split_to_table(candidate, '') AS characters(character)
        WHERE NOT public.orbit_alias_code_point_allowed(ascii(character))
      )
      THEN candidate
    ELSE 'ORBIT'
  END
  FROM minimum_length_alias
